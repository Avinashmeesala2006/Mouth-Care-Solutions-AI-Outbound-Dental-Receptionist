"""Generate the packaged telephone voice pack from the Fish Speech reference voice.

Run with the Fish Speech virtualenv (it provides httpx, ormsgpack, numpy and
faster-whisper):

    E:\\fish-speech\\.venv\\Scripts\\python.exe scripts/generate_voice_pack_http.py --publish

Every asset is generated by the running Fish Speech HTTP server (/v1/tts) using
the reference WAV and its transcript as in-context conditioning, converted to
8 kHz mono 16-bit PCM, and then verified:

* acoustic checks: plausible duration for the word count, real speech energy
  modulation (rejects constant tones and silence);
* ASR checks: a faster-whisper transcript must contain the asset keywords and
  stay within a word-error-rate bound of the canonical text.

Failed assets are regenerated with a new seed. Work is staged in
artifacts/voice-pack-staging and is only published to artifacts/voice-pack
(with a provenance manifest) when every asset passes. Re-running resumes: an
asset already verified for the same text, reference and parameters is reused.
"""
